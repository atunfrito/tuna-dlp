export const DICCIONARIOS = { es, en };

// "system" (o cualquier otra cosa) sigue al idioma de Windows: español si lo
// es, inglés si no.
export function idiomaDe(preferido) {
  if (preferido === "es" || preferido === "en") return preferido;
  return (navigator.language || "").toLowerCase().startsWith("es") ? "es" : "en";
}

export function traducir(idioma, clave, vars) {
  let s = DICCIONARIOS[idioma]?.[clave] ?? es[clave] ?? clave;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
  return s;
}

// Los errores que escribe Rust (en español) a su versión en inglés.
const ERRORES = [
  [/^esa url no es un canal$/, "that url isn't a channel"],
  [/^esa url no es una lista$/, "that url isn't a playlist"],
  [/^no se pudo lanzar yt-dlp: (.*)$/s, "couldn't start yt-dlp: $1"],
  [/^tiempo raro: (.*)$/, "that time looks off: $1"],
  [/^el final del recorte va antes del principio$/, "the trim end comes before the start"],
  [/^ffmpeg no pudo recortar: (.*)$/s, "ffmpeg couldn't trim: $1"],
  [/^github no devolvió versión$/, "github didn't return a version"],
];
export function traducirError(idioma, mensaje) {
  if (idioma !== "en" || !mensaje) return mensaje;
  for (const [patron, ingles] of ERRORES) if (patron.test(mensaje)) return mensaje.replace(patron, ingles);
  return mensaje;
}
